-- Read the luac bytecode and emit a C++ byte-array translation unit.
--
-- Invocation forms:
--   lua bin2cc.lua <in.luac> <out.cc>   (file mode; binary-safe everywhere)
--   luac -o - ... | lua bin2cc.lua > out.cc   (historical pipe mode; NOT
--   usable on Windows, where cmd.exe pipes/redirection mangle binary data)
local data
if arg and arg[1] then
    local inFile = assert(io.open(arg[1], "rb"))
    data = inFile:read("*all")
    inFile:close()
else
    data = io.read("*all")
end
if arg and arg[2] then
    io.output(assert(io.open(arg[2], "w")))
end

io.write("// Copyright 2023-2024 DreamWorks Animation LLC\n")
io.write("// SPDX-License-Identifier: Apache-2.0\n")
io.write("\n")
io.write("// WARNING: THIS FILE IS AUTOMATICALLY GENERATED BY THE BUILD!\n")
io.write("//          MODIFICATIONS TO IT WILL NOT BE SAVED!\n")
io.write("\n")
io.write("#include <cstdlib>\n")
io.write("\n")
io.write("namespace {\n")
io.write("\n")
io.write("const std::size_t bin2cc_len = " .. tostring(#data) .. ";\n")
io.write("\n")
io.write("const unsigned char bin2cc_data[bin2cc_len] = {\n")
io.write("   ")
for n = 1, #data do
    io.write(string.format(" 0x%02x", string.byte(data, n, n)))
    if n < #data then
        io.write(",")
        if n % 8 == 0 then
            io.write("\n   ")
        end
    end
end
io.write("\n};\n")
io.write("\n")
io.write("} // namespace\n")
io.write("\n")
